import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const exec = promisify(execFile);
const output = new URL('../src/generated/goRuntimeAssets.js', import.meta.url);
const moduleDir = new URL('../go-runner/', import.meta.url);
const { stdout: goRoot } = await exec('go', ['env', 'GOROOT']);
const wasmExec = new URL(`lib/wasm/wasm_exec.js`, `file://${goRoot.trim()}/`);
const tempDir = await mkdtemp(join(tmpdir(), 'blind75-go-runtime-'));
const wasmOutput = join(tempDir, 'runner.wasm');

try {
  await exec('go', ['build', '-trimpath', '-buildvcs=false', '-ldflags', '-s -w', '-o', wasmOutput, '.'], {
    cwd: moduleDir.pathname,
    env: { ...process.env, GOOS: 'js', GOARCH: 'wasm' },
    maxBuffer: 1024 * 1024 * 10,
  });

  const [wasm, loader] = await Promise.all([readFile(wasmOutput), readFile(wasmExec, 'utf8')]);
  const source = `// Generated by scripts/build-go-runtime.mjs. Do not edit.\nexport const runnerWasmBase64 = ${JSON.stringify(wasm.toString('base64'))};\nexport const wasmExecSource = ${JSON.stringify(loader)};\n`;
  await mkdir(fileURLToPath(new URL('.', output)), { recursive: true });
  await writeFile(output, source);
} finally {
  await rm(tempDir, { recursive: true, force: true });
}
